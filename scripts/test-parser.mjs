// scripts/test-parser.mjs
//
// Runs the card-set parser over mockups/parser-test-cases.json and writes
// mockups/parser-test-results.md (old = the parser in the last commit, new =
// the working copy). Exits 1 if any case fails.
//
//   node scripts/test-parser.mjs
//
// The lib files import without file extensions (Next.js style), so they're
// copied to a temp folder as .mjs with the extensions added.

import fs from 'fs';
import os from 'os';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath, pathToFileURL } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['parallelData', 'parallelDataExtra', 'parseSetFromTitle'];
const fix = (src) => src.replace(/from '\.\/([A-Za-z]+)'/g, "from './$1.mjs'");

async function load(read, label) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), `ff-parser-${label}-`));
  for (const f of FILES) {
    const src = read(f);
    if (src != null) fs.writeFileSync(path.join(dir, `${f}.mjs`), fix(src));
  }
  return (await import(pathToFileURL(path.join(dir, 'parseSetFromTitle.mjs')).href)).parseSetFromTitle;
}

const current = await load((f) => fs.readFileSync(path.join(root, 'lib', `${f}.js`), 'utf8'), 'new');
const committed = await load((f) => {
  try { return execSync(`git show HEAD:lib/${f}.js`, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }); } catch { return null; }
}, 'old').catch(() => null);

const { cases } = JSON.parse(fs.readFileSync(path.join(root, 'mockups/parser-test-cases.json'), 'utf8'));
const show = (r) => (r ? `${r.setKey}:${r.parallelKey || '-'}` : 'none');
let pass = 0, fail = 0, group = null;
const lines = [];
for (const c of cases) {
  if (c.group !== group) {
    group = c.group;
    lines.push('', `### ${group}`, '', '| Title | Sport hint | Expected | Old parser | New parser | Result |', '|---|---|---|---|---|---|');
  }
  const opts = c.sport ? { sport: c.sport } : {};
  const got = show(current(c.title, opts));
  const old = committed ? show(committed(c.title, opts)) : 'n/a';
  const ok = got === c.expect;
  ok ? pass++ : fail++;
  if (!ok) console.log(`FAIL  ${c.title}\n      expected ${c.expect}, got ${got}`);
  const title = c.title.replace(/\|/g, '/') + (c.why ? ` _(${c.why})_` : '');
  lines.push(`| ${title} | ${c.sport || ''} | ${c.expect} | ${old} | ${got} | ${ok ? 'PASS' : '**FAIL**'} |`);
}
const oldRight = committed ? cases.filter((c) => show(committed(c.title, c.sport ? { sport: c.sport } : {})) === c.expect).length : 0;
const md = `# Card-set parser test results

Real eBay titles, pulled through the site's own search on 2026-10-25 (plus a few rows from the first table). "Old parser" is the version in the last commit; "new" is this change. Expected answers were checked by hand against the checklist lists. \`setKey:-\` means the set is known but the title doesn't name the colour (the ladder lights the print-run row, or shows the base card).

Generated by \`node scripts/test-parser.mjs\` from \`mockups/parser-test-cases.json\`.

**New parser: ${pass} pass, ${fail} fail (of ${cases.length}). Old parser matched the expected answer on ${oldRight}.** Wrong-ladder answers from the new parser: ${fail ? 'see failures' : 'none'}.
${lines.join('\n')}
`;
fs.writeFileSync(path.join(root, 'mockups/parser-test-results.md'), md);
console.log(`${pass} pass, ${fail} fail of ${cases.length}; old parser right on ${oldRight}`);
process.exit(fail ? 1 : 0);
